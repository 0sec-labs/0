// Export accepted notes as a section of an AGENTS.md-style markdown file, for a person to
// review in a diff and commit. One direction only: nothing is ever imported from a repository.
import type { Note, NoteKind } from "./core.js";
import { isTrusted } from "./core.js";

export const EXPORT_BEGIN = "<!-- 0 memory: begin (generated by `0 memory export`; review before committing) -->";
export const EXPORT_END = "<!-- 0 memory: end -->";
const TITLES: Record<NoteKind | "other", string> = { command: "Commands", convention: "Conventions", "fix-decision": "Decisions", avoid: "Avoid", other: "Notes" };
const ORDER: Array<NoteKind | "other"> = ["command", "convention", "fix-decision", "avoid", "other"];

/** Only notes a person wrote. Notes a thread wrote and imports stay out. */
export const exportable = (notes: readonly Note[]): Note[] => notes.filter(note => isTrusted(note));

export function renderExportSection(notes: readonly Note[]): string {
  const lines: string[] = [EXPORT_BEGIN, "", "## Notes from 0 memory", ""];
  for (const key of ORDER) {
    const group = notes.filter(note => (note.kind ?? "other") === key).sort((a, b) => a.created.localeCompare(b.created) || a.id.localeCompare(b.id));
    if (!group.length) continue;
    lines.push(`### ${TITLES[key]}`, "", ...group.map(note => `- ${note.text}`), "");
  }
  lines.push(EXPORT_END);
  return lines.join("\n");
}

/** Put the section into existing file content: replace the generated block, or append it. Text outside the block is untouched. */
export function applyExportSection(existing: string | undefined, section: string): string {
  if (!existing?.trim()) return `${section}\n`;
  const start = existing.indexOf(EXPORT_BEGIN);
  const end = existing.indexOf(EXPORT_END);
  if (start >= 0 && end > start) return `${existing.slice(0, start)}${section}${existing.slice(end + EXPORT_END.length)}`;
  return `${existing.replace(/\s*$/, "")}\n\n${section}\n`;
}

/** Added and removed lines between two versions, for printing a reviewable change. */
export function lineChanges(before: string, after: string): { added: string[]; removed: string[] } {
  const was = new Set(before.split("\n")); const is = new Set(after.split("\n"));
  return { added: after.split("\n").filter(line => line.trim() && !was.has(line)), removed: before.split("\n").filter(line => line.trim() && !is.has(line)) };
}
