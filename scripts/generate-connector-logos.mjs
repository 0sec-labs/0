#!/usr/bin/env node
/**
 * Generates packages/cli/src/web/connector-logo-data.generated.ts from the
 * `simple-icons` devDependency (data CC0 1.0; the marks themselves remain
 * trademarks of their owners). Only the slugs below are emitted, so the shipped
 * CLI has no runtime dependency on simple-icons.
 *
 *   node scripts/generate-connector-logos.mjs
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "packages/cli/package.json"));
const icons = require("simple-icons");
import { readFileSync, readdirSync } from "node:fs";
const version = JSON.parse(readFileSync(join(root, "packages/cli/node_modules/simple-icons/package.json"), "utf8")).version;

// connector/plugin id -> simple-icons export name (siXxx). Ids absent upstream
// (Semgrep, Slack, Microsoft Teams, ...) are deliberately omitted and fall back to monograms.
const IDS = {
  github: "siGithub", elastic: "siElastic", snyk: "siSnyk", linear: "siLinear", jira: "siJira", cloudflare: "siCloudflare",
  atlassian: "siAtlassian", confluence: "siConfluence", bitbucket: "siBitbucket", gitlab: "siGitlab", notion: "siNotion",
  sentry: "siSentry", figma: "siFigma", stripe: "siStripe", datadog: "siDatadog", pagerduty: "siPagerduty", docker: "siDocker",
  vercel: "siVercel", supabase: "siSupabase", postgres: "siPostgresql", postgresql: "siPostgresql", sqlite: "siSqlite", redis: "siRedis",
  mongodb: "siMongodb", sonarqube: "siSonarqubeserver", terraform: "siTerraform", kubernetes: "siKubernetes", okta: "siOkta",
  auth0: "siAuth0", splunk: "siSplunk", grafana: "siGrafana", prometheus: "siPrometheus", jenkins: "siJenkins", circleci: "siCircleci",
  trello: "siTrello", asana: "siAsana", discord: "siDiscord", zendesk: "siZendesk", hubspot: "siHubspot", airtable: "siAirtable", postman: "siPostman",
};

const entries = {};
for (const [id, exportName] of Object.entries(IDS)) {
  const icon = icons[exportName];
  if (!icon) { console.warn(`skip ${id}: ${exportName} not in simple-icons ${version}`); continue; }
  if (!/^[MmLlHhVvCcSsQqTtAaZz0-9eE .,+-]+$/.test(icon.path)) throw new Error(`unexpected path data for ${id}`);
  entries[id] = { title: icon.title, hex: icon.hex, path: icon.path };
}
// Vendor marks that simple-icons does not ship. Source files live in scripts/extra-marks/ so generation is
// reproducible offline. Each is { file, group id of the symbol, viewBox of that symbol }; colours and proportions are untouched.
//
// semgrep: https://raw.githubusercontent.com/semgrep/semgrep/develop/images/semgrep-logo-light.svg (official semgrep/semgrep
//   repo, README logo). Semgrep publishes no brand-kit terms (semgrep.dev/brand is empty); the repo is LGPL-2.1 and the mark is a
//   registered trademark of Semgrep, Inc., used here only to identify the Semgrep integration (nominative use). Symbol only
//   (the #semgrep-ellipsis group), unmodified.
// slack, teams: NOT embedded. Slack's assets are behind a Widen portal (https://salesforce.widencollective.com/c/yn6bxnam;
//   use requires agreeing to the Slack brand guidelines/ToS, no embeddable file or third-party-integration terms published);
//   Microsoft publishes no redistributable Teams SVG. They keep monograms until a vendor file with permissive terms is obtained.
const EXTRA = {
  semgrep: { file: "semgrep.svg", group: "semgrep-ellipsis", title: "Semgrep", width: 512, height: 200 },
};
for (const [id, mark] of Object.entries(EXTRA)) {
  const svg = readFileSync(join(root, "scripts/extra-marks", mark.file), "utf8");
  if (/<script|foreignObject|href|xlink|url\(|<image|\son[a-z]+\s*=|<!ENTITY/i.test(svg)) throw new Error(`unsafe svg for ${id}`);
  const group = new RegExp(`<g id="${mark.group}"[^>]*fill="#([0-9A-Fa-f]{6})"[^>]*>([\\s\\S]*?)</g>`).exec(svg);
  if (!group) throw new Error(`group ${mark.group} not found in ${mark.file}`);
  const paths = [...group[2].matchAll(/<path d="([^"]+)"\s*\/>/g)].map(m => m[1]);
  if (!paths.length || paths.some(d => !/^[MmLlHhVvCcSsQqTtAaZz0-9eE .,+-]+$/.test(d))) throw new Error(`unexpected path data for ${id}`);
  if (paths.join("").length > 8000) throw new Error(`mark too large for ${id}`);
  entries[id] = { title: mark.title, hex: group[1], path: paths[0], paths, width: mark.width, height: mark.height };
}
const body = Object.entries(entries).map(([id, v]) => `  ${JSON.stringify(id)}: ${JSON.stringify(v)},`).join("\n");
writeFileSync(join(root, "packages/cli/src/web/connector-logo-data.generated.ts"), `// GENERATED by scripts/generate-connector-logos.mjs from simple-icons@${version} — do not edit.
// Icon data: CC0 1.0 (https://github.com/simple-icons/simple-icons); extra vendor marks from scripts/extra-marks (see generator for sources). Brand marks remain trademarks of their respective owners.
export interface BrandLogo { readonly title: string; readonly hex: string; readonly path: string; readonly paths?: readonly string[]; readonly width?: number; readonly height?: number }
export const BRAND_LOGOS: Readonly<Record<string, BrandLogo>> = {
${body}
};
`);
console.log(`wrote ${Object.keys(entries).length} logos`);
