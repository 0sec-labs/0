import test from "node:test";
import assert from "node:assert/strict";
import {mkdtemp,rm} from "node:fs/promises";
import {resolve} from "node:path";
import {fileURLToPath,pathToFileURL} from "node:url";
import {build} from "esbuild";
const root=fileURLToPath(new URL("../",import.meta.url));
test("tool details omit binary image bytes and browser captures stay in the browser workspace",async()=>{
  const dashboard=resolve(root,"packages/dashboard");
  const directory=await mkdtemp(resolve(dashboard,".tool-presentation-test-"));
  try {
    const output=resolve(directory,"fixture.mjs");
    await build({stdin:{contents:`import React from 'react';import {renderToStaticMarkup} from 'react-dom/server';import {ToolActivity} from './src/console/tool-activity';export const renderActivity=calls=>renderToStaticMarkup(React.createElement(ToolActivity,{calls}));export {toolPayloadText} from './src/console/tool-activity';export {toolImages,transcriptToolImages} from './src/console/inline-image';import {ToolCatalog} from './src/console/tool-catalog';export {filterToolCatalog,toolCatalogGroup} from './src/console/tool-catalog';export const renderCatalog=tools=>renderToStaticMarkup(React.createElement(ToolCatalog,{tools}));`,resolveDir:dashboard,loader:"tsx"},outfile:output,bundle:true,platform:"node",format:"esm",packages:"external",jsx:"automatic",alias:{"@":resolve(dashboard,"src")},logLevel:"silent"});
    const {toolPayloadText,toolImages,transcriptToolImages,renderActivity,renderCatalog,filterToolCatalog,toolCatalogGroup}=await import(pathToFileURL(output).href);
    const tools=[{name:"read_file",description:"Read workspace files",inputSchema:{secretSchemaMarker:true}},{name:"mcp__zeroverse__scan",description:"Scan target",inputSchema:{}},{name:"mcp__custom__read_file",description:"Read remote files",inputSchema:{}}];
    assert.deepEqual(filterToolCatalog(tools," READ   workspace ").map(tool=>tool.name),["read_file"]);
    assert.equal(filterToolCatalog(tools,"no match").length,0);
    assert.equal(filterToolCatalog(tools," ").length,3);
    assert.deepEqual(tools.map(tool=>toolCatalogGroup(tool.name)),["Built-in tools","0verse","Extensions"]);
    const catalog=renderCatalog(tools);
    assert.match(catalog,/Available tools · 3/);
    assert.match(catalog,/This count does not show how many have run/);
    assert.match(catalog,/Search available tools/);
    assert.doesNotMatch(catalog,/secretSchemaMarker/,"closed tool details do not serialize schemas");
    assert.equal(renderCatalog([]),"");
    const activity=renderActivity([{id:"plan",name:"update_todos",arguments:{},result:{ok:true},isRunning:false},{id:"read",name:"read_file",arguments:{},result:"ok",isRunning:false}]);
    assert.match(activity,/Used 2 tools/);
    assert.match(activity,/lucide-list-checks/);
    assert.match(activity,/lucide-file-text/);
    assert.doesNotMatch(activity,/lucide-wrench/);
    assert.match(activity,/Used: Plan, Files/);
    assert.match(activity,/rounded-full bg-muted/);
    assert.doesNotMatch(activity,/steps|Tools ·/);
    const sources=renderActivity([{id:"web",name:"web_search",arguments:{},result:{sources:[{url:"https://docs.example.com/page"},{url:"https://docs.example.com/another"},{url:"https://other.example.com/a"}]},isRunning:false}]);
    assert.match(sources,/2 sources/);
    assert.match(sources,/href="https:\/\/docs.example.com"/);
    assert.doesNotMatch(sources,/Searched 2 websites/);
    const receipt={meta:{image:{mimeType:"image/png",imageBase64:"AAAA"}},output:{message:"Screenshot captured"}};
    assert.equal(toolImages(receipt).length,1,"browser workspace still has the capture");
    assert.equal(transcriptToolImages("browser_screenshot",receipt).length,0);
    assert.equal(transcriptToolImages("mcp__computer__capture",receipt).length,0);
    assert.equal(transcriptToolImages("image_gen",receipt).length,1,"generated images remain inline");
    const detail=toolPayloadText(receipt);
    assert.match(detail,/Screenshot captured/);
    assert.doesNotMatch(detail,/AAAA/);
    assert.doesNotMatch(toolPayloadText(JSON.stringify(receipt)),/AAAA/,"serialized MCP receipts also hide binary bytes");
    assert.match(detail,/image data; see preview/);
    assert.doesNotMatch(toolPayloadText({content:[{type:"image",data:"raw-binary-bytes"}]}),/raw-binary-bytes/);
    assert.match(toolPayloadText({data:"ordinary tool data"}),/ordinary tool data/);
    assert.equal(toolPayloadText("Plain output"),"Plain output");
  }finally{await rm(directory,{recursive:true,force:true});}
});
